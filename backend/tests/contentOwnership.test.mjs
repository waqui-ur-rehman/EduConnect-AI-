import test from "node:test";
import assert from "node:assert/strict";
import { canEditOwnedResource, canReadOwnedResource, canViewAllContent } from "../src/utils/contentAuthorization.js";
const teacherA = { _id: "teacher-A", role: "teacher" };
const teacherB = { _id: "teacher-B", role: "teacher" };
const student = { _id: "student-A", role: "student" };
const admin = { _id: "admin-A", role: "admin" };
const draft = { teacherId: "teacher-A", status: "draft" };
const published = { teacherId: "teacher-A", status: "published", published: true, approvedVersion: { title: "Reviewed version" } };
test("course/book owner can edit own resource", () => assert.equal(canEditOwnedResource(teacherA,draft),true));
test("different teacher cannot edit", () => assert.equal(canEditOwnedResource(teacherB,draft),false));
test("student cannot edit teacher-owned content", () => assert.equal(canEditOwnedResource(student,published),false));
test("admin cannot silently bypass teacher ownership", () => assert.equal(canEditOwnedResource(admin,draft),false));
test("draft cannot be read by other teachers or students", () => { assert.equal(canReadOwnedResource(student,draft),false); assert.equal(canReadOwnedResource(teacherB,draft),false); });
test("published can be read by student", () => assert.equal(canReadOwnedResource(student,published),true));
test("legacy published status alone grants no student access", () => assert.equal(canReadOwnedResource(student,{ teacherId: "teacher-A", status: "published" }),false));
test("anonymous cannot read restricted content", () => assert.equal(canReadOwnedResource(null,published),false));
test("owner can read own draft", () => assert.equal(canReadOwnedResource(teacherA,draft),true));
test("anonymous cannot edit", () => assert.equal(canEditOwnedResource(null,draft),false));
test("admin listing is explicitly admin only", () => { assert.equal(canViewAllContent(admin),true); assert.equal(canViewAllContent(teacherA),false); });
